/** Category icons are data (kebab-case lucide names). Unknown names fall back to a plain circle. */
export const CATEGORY_ICONS: Record<string, LucideIcon> = {
  banknote: Banknote,
  bike: Bike,
  "book-open": BookOpen,
  briefcase: Briefcase,
  bus: Bus,
  car: Car,
  circle: Circle,
  coffee: Coffee,
  coins: Coins,
  dumbbell: Dumbbell,
  fuel: Fuel,
  gift: Gift,
  "graduation-cap": GraduationCap,
  "heart-handshake": HeartHandshake,
  house: House,
  home: House,
  landmark: Landmark,
  plane: Plane,
  "party-popper": PartyPopper,
  "paw-print": PawPrint,
  phone: Phone,
  "piggy-bank": PiggyBank,
  receipt: Receipt,
  repeat: Repeat,
  shirt: Shirt,
  "shopping-bag": ShoppingBag,
  "shopping-cart": ShoppingCart,
  smartphone: Smartphone,
  sparkles: Sparkles,
  stethoscope: Stethoscope,
  tv: Tv,
  user: User,
  users: Users,
  utensils: Utensils,
  wallet: Wallet,
  wifi: Wifi,
  wrench: Wrench,
  zap: Zap,
};

export function CategoryIcon({ name, ...props }: { name: string | undefined } & LucideProps) {
  const Icon = (name && CATEGORY_ICONS[name]) || Circle;
  return <Icon aria-hidden {...props} />;
}
